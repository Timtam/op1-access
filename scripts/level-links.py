"""Which area leads where in Octopath Traveler: writes Scripts/worldlinks.lua for the
world map's route finder (main.lua, M.wm_graph).

The game has no table of its area links: every exit is a LevelTrigger actor in its level,
m_nNextMapID the level it leads to. This reads them from the cooked area levels.

1. Extract the area levels from the game's pak (repak, see tools/):
       repak unpack -q -o <out> -i Octopath_Traveler/Content/Level/Area
           "<game>/Octopath_Traveler/Content/Paks/Octopath_Traveler-WindowsNoEditor.pak"
2. python -I scripts/level-links.py <out>/Octopath_Traveler/Content/Level/Area
       scripts/Mods/OP1Access/Scripts/worldlinks.lua

For each .umap, the package's name map gives the indices of "m_nNextMapID" and
"IntProperty"; the exports (.uexp) hold each exit's tagged property
    Name(FName) Type(FName) Size=4 ArrayIndex=0 HasGuid=0 Value(int32)
UE 4.18, unversioned packages (FileVersionUE4 0 = the engine's own, 516: names carry two
hash words). The output is { ["F_Plain_1_2"] = { 79, 82, 85, 142 }, ... }: level name ->
destination level IDs, numbers only, no game text. 2026-11-14: 179 levels, 416 exits.
"""
import os
import struct
import sys


def read_names(path):
    with open(path, "rb") as f:
        b = f.read()
    o = 0

    def i32():
        nonlocal o
        v = struct.unpack_from("<i", b, o)[0]
        o += 4
        return v

    tag = struct.unpack_from("<I", b, 0)[0]
    if tag != 0x9E2A83C1:
        raise ValueError("not a package")
    o = 4
    legacy = i32()
    if legacy != -4:
        i32()  # LegacyUE3Version
    ue4ver = i32()
    if ue4ver == 0:
        ue4ver = 516  # unversioned (cooked) package: the engine's own, 4.18
    i32()  # licensee version
    if legacy <= -2:
        n = i32()  # custom versions
        o += n * 8 if legacy == -2 else n * 20
    i32()  # TotalHeaderSize
    flen = i32()  # FolderName
    o += flen if flen >= 0 else -flen * 2
    o += 4  # PackageFlags
    name_count = i32()
    name_offset = i32()
    names = []
    o = name_offset
    for _ in range(name_count):
        ln = i32()
        if ln >= 0:
            s = b[o:o + ln - 1].decode("latin-1")
            o += ln
        else:
            s = b[o:o - ln * 2 - 2].decode("utf-16-le")
            o += -ln * 2
        if ue4ver >= 504:
            o += 4
        names.append(s)
    return names


def links(umap):
    names = read_names(umap)
    try:
        nid = names.index("m_nNextMapID")
        tid = names.index("IntProperty")
    except ValueError:
        return []
    pat = struct.pack("<iiiiiiB", nid, 0, tid, 0, 4, 0, 0)
    out = []
    for p in (umap[:-5] + ".uexp", umap):
        if not os.path.exists(p):
            continue
        with open(p, "rb") as f:
            data = f.read()
        i = data.find(pat)
        while i >= 0:
            out.append(struct.unpack_from("<i", data, i + len(pat))[0])
            i = data.find(pat, i + 1)
    return out


def main():
    root, outpath = sys.argv[1], sys.argv[2]
    result = {}
    total = 0
    for dirpath, _, files in os.walk(root):
        for fn in files:
            if not fn.endswith(".umap"):
                continue
            try:
                ids = links(os.path.join(dirpath, fn))
            except Exception as e:  # noqa: BLE001 - report and go on
                print("skip", fn, e)
                continue
            if ids:
                result[fn[:-5]] = sorted(set(ids))
                total += len(ids)
    with open(outpath, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by scripts/level-links.py from the game's area levels: each level's\n")
        f.write("-- exits (LevelTrigger m_nNextMapID) as destination level IDs. Data only, no game text.\n")
        f.write("return {\n")
        for lv in sorted(result):
            f.write('    ["%s"] = { %s },\n' % (lv, ", ".join(str(v) for v in result[lv])))
        f.write("}\n")
    print("levels with exits:", len(result), "exit properties:", total)


if __name__ == "__main__":
    main()
